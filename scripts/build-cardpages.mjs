/**
 * Builds the list of cards we treat as published pages.
 *
 *   node scripts/build-cardpages.mjs            # writes apps/public/lib/published-cards.js
 *   node scripts/build-cardpages.mjs --dry-run  # report only
 *
 * Card URLs are /card/<query>, so any string is a valid page and there is no
 * fixed set of them. This is the set we CHOOSE to stand behind: the ones the
 * warmer keeps priced, the sitemap advertises, and the server renders a price
 * into rather than leaving to the browser.
 *
 * WHY NOT EVERY CARD. The catalogue holds ~32,000 English rows and most price
 * badly or not at all — commons whose eBay market is a pick-list, sealed
 * product, World Championship decks. Publishing those is not extra reach, it
 * is thousands of near-identical pages carrying a caveat instead of an answer,
 * which is what gets a site demoted — and the demotion lands on the good pages
 * too. So the published set is the chase set: the 455 cards in bigset-en2.json,
 * measured at 100% priced, 15+ median comps and 90% with art.
 *
 * It is also a budget. Every published card is a card to keep warm, and on a
 * 2,000-request month that is the binding constraint (see warm-cardpages.mjs).
 *
 * The entry carries the catalogue id and the query string. The id is the
 * truth — names and images are read from the catalogue at render time so a
 * later backfill shows up without a rebuild — and the query is only an index,
 * for matching an incoming URL to a card without a database round trip.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { queryForCard, normaliseQuery } from "../apps/public/lib/card-query.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "scripts/bigset-en2.json");
const OUT = join(ROOT, "apps/public/lib/published-cards.js");
const dryRun = process.argv.includes("--dry-run");

const source = JSON.parse(readFileSync(SOURCE, "utf8"));
const entries = [];
const seen = new Map();
const problems = [];

for (const card of source) {
  if (card.game && card.game !== "pokemon") { problems.push(`not Pokémon: ${card.name}`); continue; }
  if (!card.id) { problems.push(`no catalogue id: ${card.name} ${card.number || ""}`); continue; }
  const q = queryForCard(card);
  if (!q) { problems.push(`empty query: ${JSON.stringify(card)}`); continue; }

  // Two cards sharing a query would price one under the other's name, and
  // whichever the resolver picked would silently own the other's page.
  const key = normaliseQuery(q);
  const prior = seen.get(key);
  if (prior) {
    if (prior.id !== card.id) problems.push(`COLLISION on "${q}": ${prior.id} and ${card.id}`);
    continue;
  }
  seen.set(key, card);
  entries.push({ id: card.id, q });
}

entries.sort((a, b) => a.q.localeCompare(b.q));
const collisions = problems.filter((p) => p.startsWith("COLLISION"));
for (const p of problems) console.warn(`  ${p}`);
if (collisions.length) {
  console.error(`\n${collisions.length} query collision(s). Two cards on one page is worse than no page.`);
  process.exit(1);
}

console.log(`${entries.length} cards${problems.length ? `, ${problems.length} skipped` : ""}${dryRun ? " (dry run)" : ""}`);
if (!dryRun) {
  writeFileSync(OUT, `/**
 * GENERATED by scripts/build-cardpages.mjs — do not edit by hand.
 *
 * The cards we stand behind: kept warm, listed in the sitemap, and server
 * rendered with a price. \`id\` is the catalogue row; \`q\` is the query string
 * its URL carries, used only to match an incoming /card/<query> to a card.
 *
 * ${entries.length} cards.
 */
export default ${JSON.stringify(entries, null, 1)};
`);
  console.log(`wrote ${OUT.replace(ROOT + "/", "")}`);
}
